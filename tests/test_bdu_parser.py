"""Тест парсера выгрузки БДУ ФСТЭК (на синтетических строках в формате выгрузки).

Не требует реального 34 МБ xlsx: parse_rows работает со списком кортежей,
как их отдаёт openpyxl (values_only=True).
"""
from scanner.feeds.bdu_fstec import parse_rows


# Воспроизводим раскладку реальной выгрузки: строки 1-2 — групповые заголовки,
# строка 3 — имена колонок, далее данные.
HEADER = [
    "Идентификатор", "Наименование уязвимости", "Описание уязвимости",
    "Вендор ПО", "Название ПО", "Версия ПО", "Тип ПО",
    "Наименование ОС и тип аппаратной платформы", "Класс уязвимости",
    "Дата выявления", "CVSS 2.0", "CVSS 3.0", "CVSS 4.0",
    "Уровень опасности уязвимости", "Возможные меры по устранению",
    "Статус уязвимости", "Наличие эксплойта", "Информация об устранении",
    "Ссылки на источники", "Идентификаторы других систем описаний уязвимости",
]


def _row(bdu_id, other_ids, severity_text):
    r = [None] * len(HEADER)
    r[0] = bdu_id
    r[1] = "Тестовая уязвимость"
    r[19] = other_ids
    r[13] = severity_text
    return tuple(r)


def _rows():
    return [
        ("Описание уязвимостей",) + (None,) * (len(HEADER) - 1),  # строка 1
        ("Общая информация",) + (None,) * (len(HEADER) - 1),      # строка 2
        tuple(HEADER),                                            # строка 3 — заголовок
        _row("BDU:2014-00002", "CVE-2013-5946, OSVDB ID:100840, Bugtraq ID:64172",
             "Критический уровень опасности (базовая оценка CVSS 2.0 составляет 10)"),
        _row("BDU:2015-01000", "нет данных",
             "Средний уровень опасности (базовая оценка CVSS 3.0 составляет 5,3)"),
        _row("не-BDU-строка", "CVE-9999-0001", ""),               # должна отсеяться
    ]


def test_parse_basic():
    recs = list(parse_rows(_rows()))
    assert [r.bdu_id for r in recs] == ["BDU:2014-00002", "BDU:2015-01000"]


def test_cve_extraction():
    recs = list(parse_rows(_rows()))
    assert recs[0].cve_ids == ["CVE-2013-5946"]
    assert recs[1].cve_ids == []  # нет CVE в "нет данных"


def test_cvss_score_from_text():
    recs = list(parse_rows(_rows()))
    assert recs[0].cvss_score == 10.0
    assert recs[1].cvss_score == 5.3  # запятая как десятичный разделитель
