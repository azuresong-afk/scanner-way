@pytest.mark.parametrize(("a", "b", "sign"), DPKG_CASES)
def test_dpkg_compare(a, b, sign):
    r = dpkg_compare(a, b)
    assert (r > 0) - (r < 0) == sign
    r = dpkg_compare(b, a)
    assert (r > 0) - (r < 0) == -sign


@pytest.mark.skipif(shutil.which("dpkg") is None, reason="нет dpkg для сверки")
@pytest.mark.parametrize(("a", "b", "sign"), DPKG_CASES)
def test_dpkg_compare_agrees_with_dpkg(a, b, sign):
    op = {-1: "lt", 0: "eq", 1: "gt"}[sign]
    assert subprocess.run(["dpkg", "--compare-versions", a, op, b], check=False).returncode == 0


@pytest.mark.parametrize(("a", "b", "sign"), RPM_CASES)
def test_rpm_compare(a, b, sign):
    r = rpm_compare(a, b)
    assert (r > 0) - (r < 0) == sign


def test_parsers_and_dispatch():
    assert parse_dpkg("1:9.2p1-2+deb12u3") == (1, "9.2p1", "2+deb12u3")
    assert parse_dpkg("1.0-1-2") == (0, "1.0-1", "2")      # ревизия — после последнего '-'
    assert parse_dpkg("5.1.16") == (0, "5.1.16", "")
    assert parse_evr("1:3.0.7-27.el9") == (1, "3.0.7", "27.el9")
    assert parse_evr("(none):8.8p1-6.el7") == (0, "8.8p1", "6.el7")
    assert compare("dpkg", "2.0~rc1", "2.0") < 0
    assert compare("rpm", "2.0~rc1", "2.0") < 0
    with pytest.raises(ValueError):
        compare("apk", "1", "2")
    assert strip_zero_epoch("0:3.0.2-0ubuntu1.15") == "3.0.2-0ubuntu1.15"
